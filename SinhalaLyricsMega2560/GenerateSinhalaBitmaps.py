"""Regenerate SinhalaLyricsBitmaps.h from Noto Sans Sinhala.

Requires: Python 3, Pillow with libraqm support.  The ready-to-upload header
is already included, so this script is only needed if you change the lyrics.
The font is downloaded from Google Fonts (SIL Open Font License).
"""
from pathlib import Path
from urllib.request import urlretrieve

from PIL import Image, ImageDraw, ImageFont, features

FONT_URL = ("https://github.com/google/fonts/raw/main/ofl/notosanssinhala/"
            "NotoSansSinhala%5Bwdth,wght%5D.ttf")
FONT_FILE = Path("NotoSansSinhala-Variable.ttf")
OUTPUT = Path("SinhalaLyricsBitmaps.h")
LYRICS = [
    "නපුරුයි කතා", "සොඳුරුයි සිනා", "මගේ හිත පාරනා", "සායම් එපා",
    "මායම් එපා", "පියාඹන්නේ", "තනියෙන් තමා",
]
PIXEL_SIZE = 15

if not features.check_feature("raqm"):
    raise SystemExit("Pillow needs libraqm for correct Sinhala text shaping.")
if not FONT_FILE.exists():
    urlretrieve(FONT_URL, FONT_FILE)

font = ImageFont.truetype(FONT_FILE, PIXEL_SIZE, layout_engine=ImageFont.Layout.RAQM)

def xbm_bytes(text):
    # Render with a generous margin, then crop.  Pixels are packed LSB-first,
    # the XBM format expected by U8g2.drawXBMP() for flash-stored bytes.
    box = font.getbbox(text)
    im = Image.new("1", (box[2] - box[0] + 8, box[3] - box[1] + 8), 0)
    ImageDraw.Draw(im).text((4 - box[0], 4 - box[1]), text, font=font, fill=1)
    crop = im.getbbox()
    im = im.crop(crop)
    w, h = im.size
    rows = (w + 7) // 8
    data = []
    for y in range(h):
        for byte_x in range(rows):
            value = 0
            for bit in range(8):
                x = byte_x * 8 + bit
                if x < w and im.getpixel((x, y)):
                    value |= 1 << bit
            data.append(value)
    return w, h, data

out = [
    "#pragma once", "#include <Arduino.h>",
    "// Generated by GenerateSinhalaBitmaps.py using Noto Sans Sinhala (OFL).",
    "// 1-bit, LSB-first XBM line art; data stays in flash via PROGMEM.",
    "struct SinhalaLine { uint8_t width; uint8_t height; const uint8_t *bitmap; };",
    "// AVR code must use memcpy_P() to read this PROGMEM lookup table.",
    "",
]
line_refs = []
for n, lyric in enumerate(LYRICS):
    w, h, data = xbm_bytes(lyric)
    name = f"sinhalaLine{n}"
    out.append(f"static const uint8_t {name}[] PROGMEM = {{")
    for i in range(0, len(data), 12):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i+12]) + ",")
    out.append("};")
    out.append("")
    line_refs.append(f"  {{{w}, {h}, {name}}},  // {lyric}")
out += ["static const SinhalaLine sinhalaLines[] PROGMEM = {", *line_refs, "};",
        "constexpr uint8_t SINHALA_LINE_COUNT = sizeof(sinhalaLines) / sizeof(sinhalaLines[0]);", ""]
OUTPUT.write_text("\n".join(out), encoding="utf-8")
print(f"Wrote {OUTPUT} with {len(LYRICS)} shaped Sinhala lines.")
